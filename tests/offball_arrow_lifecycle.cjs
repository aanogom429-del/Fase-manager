const assert=require('node:assert/strict'),{env}=require('./continuity.cjs');
const e=env(),s=e.t.get(),p=s.players.find(p=>p.t===0&&p.n===8);
const overlay=()=>e.nodes['offball-overlay'].innerHTML;
const arrows=()=> (overlay().match(/marker-end=/g)||[]).length;
e.t.queueOffBall(p.id,'move',{x:65,y:48});
assert.equal(arrows(),1);assert.match(overlay(),/stroke-dasharray="6 5"/);
e.t.commitOffBall();e.t.render();
assert.equal(arrows(),1,'active order must remain visible');assert.match(overlay(),/stroke-dasharray="none"/);
const initial=Math.hypot(p.x-65,p.y-48),before=overlay();
e.t.playChoice('safety');
for(let n=0;n<4000&&['resolve','settle'].includes(e.t.get().stage);n++)e.tick();
assert(Math.hypot(p.x-65,p.y-48)<initial,'player must approach drawn destination during the pass');
assert.notEqual(overlay(),before,'arrow origin follows physical movement');
assert.equal(arrows(),1);
e.t.prepareDecision();e.t.queueOffBall(p.id,'move',{x:70,y:50});
assert.equal(arrows(),1,'replacement preview must not duplicate active order');
assert.match(overlay(),/stroke-dasharray="6 5"/);
e.t.commitOffBall();e.t.get().offBallOrders[0].until=0;e.t.pruneOffBall();e.t.render();
assert.equal(arrows(),0,'expired orders must disappear');
console.log('PASS: planned/active arrow, physical movement, moving origin, replacement and expiry');
